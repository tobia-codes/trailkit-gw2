//! `cargo xtask tokens [--check]`: generates the theme values and the token
//! reference from the token files in `design/tokens/` (ROADMAP R84, R118).
//!
//! The token files are the only source of the values: they become
//! `trailkit-ui/src/theme/values.rs` (Q455) and the reference
//! `token-values.md` with every token's purpose (Q456). The test
//! [`tests::the_generated_files_are_current`] fails in `cargo test`
//! (pre-push hook and CI) when either file is out of date.

use std::{
    fs,
    io::Write as _,
    path::Path,
    process::{Command, Stdio},
};

use anyhow::{Context, Result, bail};

use self::source::{ColorValue, Group, TokenValue, Unit, read_groups};
use crate::workspace;

mod rust_values;
mod source;

/// The token files, relative to the repository root.
const TOKENS_DIRECTORY: &str = "design/tokens";

/// The generated reference, relative to the repository root.
const DOCUMENT_PATH: &str = ".agents/skills/trailkit-ui/references/token-values.md";

/// The generated theme values, relative to the Cargo workspace root.
const VALUES_PATH: &str = "addons/crates/trailkit-ui/src/theme/values.rs";

/// What `cargo xtask tokens` does.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// Rewrite the generated files.
    Write,
    /// Fail if a generated file differs from the token files.
    Check,
}

/// `color` as shown in the reference: `#RRGGBB`, with its alpha if
/// translucent.
fn format_color(color: ColorValue) -> String {
    match color {
        ColorValue::Opaque(rgb) => format!("#{rgb:06X}"),
        ColorValue::WithAlphaByte(rgba) => {
            let alpha = f64::from(rgba & 0xFF) / 255.0;
            format!("#{:06X} at {:.0} %", rgba >> 8, alpha * 100.0)
        }
        ColorValue::WithAlpha(rgb, alpha) => format!("#{rgb:06X} at {:.0} %", alpha * 100.0),
    }
}

/// A number as shown in the reference: `4 px`, `1.5 × font size`.
fn format_number(value: f64, unit: Unit) -> String {
    match unit {
        Unit::Pixels => format!("{value} px"),
        Unit::FontSize => format!("{value} × font size"),
        Unit::BodySize => format!("{value:.2} × body size"),
    }
}

/// Who uses the tokens of a section, for the reference.
fn section_note(section: &str) -> &'static str {
    match section {
        "shared" => "Shared by the addons and the web.",
        "addon" => "Addons only.",
        "web" => "Web only.",
        _ => "",
    }
}

/// The reference document for `groups`.
fn render_document(groups: &[Group]) -> String {
    let mut document = String::from(
        "# Token values\n\n\
         Generated by `cargo xtask tokens` from [`design/tokens/`](../../../../design/tokens/);\n\
         do not edit by hand. `cargo test` fails when this file is out of date. When\n\
         to use which token is binding in [`tokens.md`](tokens.md).\n",
    );
    for group in groups {
        if let Some(title) = &group.title {
            document.push_str(&format!(
                "\n## {title}\n\n{}\n\n| Token | Dark | Light | Purpose |\n| --- | --- | --- | --- |\n",
                section_note(&group.section)
            ));
        }
        for token in &group.tokens {
            let (dark, light) = match token.value {
                TokenValue::Colors { dark, light } => (format_color(dark), format_color(light)),
                TokenValue::Number { value, unit } => {
                    let shown = format_number(value, unit);
                    (shown.clone(), shown)
                }
            };
            document.push_str(&format!(
                "| `{}` | {dark} | {light} | {} |\n",
                token.name, token.purpose
            ));
        }
    }
    document
}

/// `source` formatted by `rustfmt`, so the generated file passes
/// `cargo fmt --check`.
///
/// # Errors
/// Returns an error if `rustfmt` cannot be run or rejects the source.
fn rustfmt(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .current_dir(workspace::workspace_root())
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("failed to run `rustfmt`")?;
    child
        .stdin
        .take()
        .context("no stdin for `rustfmt`")?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "`rustfmt` rejected the generated values:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("`rustfmt` printed non-UTF-8 text")
}

/// Whether `committed` is `generated`, whatever line endings the checkout gave
/// it: Git may check text files out with CRLF on Windows.
fn is_same_document(committed: &str, generated: &str) -> bool {
    committed.replace("\r\n", "\n") == generated
}

/// Writes `content` to `path`, or in [`Mode::Check`] verifies it.
///
/// # Errors
/// Returns an error if the file cannot be read or written, or — in
/// [`Mode::Check`] — if it is out of date.
fn write_or_check(mode: Mode, path: &Path, shown: &str, content: &str) -> Result<()> {
    match mode {
        Mode::Write => {
            fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
            println!("wrote {shown}");
        }
        Mode::Check => {
            let committed =
                fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
            if !is_same_document(&committed, content) {
                bail!("{shown} is out of date; run `cargo xtask tokens`");
            }
        }
    }
    Ok(())
}

/// Generates or checks the theme values and the reference.
///
/// # Errors
/// Returns an error if a token file is malformed, `rustfmt` fails, or a
/// file cannot be written — or, in [`Mode::Check`], is out of date.
pub fn run(mode: Mode) -> Result<()> {
    let repository = workspace::repository_root();
    let groups = read_groups(&repository.join(TOKENS_DIRECTORY))?;
    let values = rustfmt(&rust_values::render(&groups)?)?;
    write_or_check(
        mode,
        &workspace::workspace_root().join(VALUES_PATH),
        VALUES_PATH,
        &values,
    )?;
    write_or_check(
        mode,
        &repository.join(DOCUMENT_PATH),
        DOCUMENT_PATH,
        &render_document(&groups),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_files_are_current() {
        if let Err(error) = run(Mode::Check) {
            panic!("{error:#}");
        }
    }

    #[test]
    fn line_endings_of_the_checkout_do_not_matter() {
        assert!(is_same_document("a\r\nb\r\n", "a\nb\n"));
        assert!(is_same_document("a\nb\n", "a\nb\n"));
        assert!(!is_same_document("a\r\nc\r\n", "a\nb\n"));
    }

    #[test]
    fn values_are_formatted_for_reading() {
        assert_eq!(format_color(ColorValue::Opaque(0x0F1318)), "#0F1318");
        assert_eq!(
            format_color(ColorValue::WithAlpha(0x0F1318, 0.24)),
            "#0F1318 at 24 %"
        );
        assert_eq!(
            format_color(ColorValue::WithAlphaByte(0x0507_0AB8)),
            "#05070A at 72 %"
        );
        assert_eq!(format_number(4.0, Unit::Pixels), "4 px");
        assert_eq!(format_number(1.5, Unit::FontSize), "1.5 × font size");
        assert_eq!(format_number(1.3, Unit::BodySize), "1.30 × body size");
    }
}
